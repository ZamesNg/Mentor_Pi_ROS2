Glyph LookupGlyph(char character) {
  const auto code = static_cast<unsigned char>(character);
  if (code >= 0x20U && code <= 0x7eU) {
    return kPrintableAsciiGlyphs[code - 0x20U];
  }
  return kPrintableAsciiGlyphs[static_cast<std::size_t>('?' - ' ')];
}

Result ToResult(IoStatus status, std::uint16_t detail = 0U) {
  switch (status) {
    case IoStatus::kOk:
      return OkResult();
    case IoStatus::kBusy:
      return {ResultCode::kBusy, detail};
    case IoStatus::kTimeout:
      return {ResultCode::kTimeout, detail};
    case IoStatus::kIoError:
      return {ResultCode::kIoError, detail};
  }
  return {ResultCode::kIoError, detail};
}

std::size_t AppendUnsigned(std::uint16_t value, char* output,
                           std::size_t capacity) {
  std::array<char, 5> reverse{};
  std::size_t digits = 0U;
  do {
    reverse[digits] = static_cast<char>('0' + (value % 10U));
    value = static_cast<std::uint16_t>(value / 10U);
    ++digits;
  } while (value != 0U && digits < reverse.size());
  const std::size_t count = digits < capacity ? digits : capacity;
  for (std::size_t index = 0; index < count; ++index) {
    output[index] = reverse[digits - index - 1U];
  }
  return count;
}

